// Vendors icon SVGs into assets/icons/ and generates assets/icons.js.
//   - Feature icons: Phosphor Icons duotone (MIT) — https://phosphoricons.com
//   - Brand logos:   Simple Icons (CC0)           — https://simpleicons.org
// Run: node scripts/build-icons.mjs   (needs network on first run; cached SVGs are reused after)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const PHOSPHOR = 'https://cdn.jsdelivr.net/npm/@phosphor-icons/core@2.1.1/assets/duotone'
const SIMPLE = 'https://cdn.jsdelivr.net/npm/simple-icons@16.33.0'

// key used in index.html (data-icon) -> phosphor duotone name
const FEATURE = {
  phoneCall: 'phone-call',
  phoneX: 'phone-x',
  night: 'moon-stars',
  followUp: 'envelope-simple',
  linkBreak: 'link-break',
  chat: 'chat-circle-dots',
  waveform: 'waveform',
  sparkle: 'sparkle',
  sealCheck: 'seal-check',
  check: 'check-circle',
  calendar: 'calendar-check',
  wallet: 'wallet',
  pin: 'map-pin',
  house: 'house-line',
  workflow: 'flow-arrow',
  chats: 'chats-circle',
  graph: 'graph',
  userCheck: 'user-circle-check',
  arrow: 'arrow-right',
  buildings: 'buildings',
}

// key -> simple-icons slug (Salesforce, Twilio, OpenAI, Outlook were removed upstream at the brands' request)
const BRANDS = {
  whatsapp: 'whatsapp',
  gmail: 'gmail',
  hubspot: 'hubspot',
  notion: 'notion',
  googlecalendar: 'googlecalendar',
  calendly: 'calendly',
  zapier: 'zapier',
  make: 'make',
  claude: 'claude',
  gemini: 'googlegemini',
  n8n: 'n8n',
}

const root = fileURLToPath(new URL('..', import.meta.url))
const dir = (p) => (mkdirSync(root + p, { recursive: true }), root + p)
const featDir = dir('assets/icons/phosphor/')
const brandDir = dir('assets/icons/brands/')

async function cached(path, url) {
  if (existsSync(path)) return readFileSync(path, 'utf8')
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  const txt = await res.text()
  writeFileSync(path, txt)
  return txt
}

const icons = {}
for (const [key, name] of Object.entries(FEATURE)) {
  const svg = await cached(`${featDir}${name}-duotone.svg`, `${PHOSPHOR}/${name}-duotone.svg`)
  // tag the secondary (tinted) layer so CSS can colour it independently
  icons[key] = svg.replace(/opacity="0\.2"/g, 'class="duo"')
}

const metaPath = `${brandDir}_simple-icons.json`
const meta = JSON.parse(await cached(metaPath, `${SIMPLE}/data/simple-icons.json`))
const hexBySlug = {}
for (const m of meta) {
  const slug = m.slug || m.title.toLowerCase().replace(/[^a-z0-9]/g, '')
  hexBySlug[slug] = m.hex
}
const brandHex = {}
for (const [key, slug] of Object.entries(BRANDS)) {
  const svg = await cached(`${brandDir}${slug}.svg`, `${SIMPLE}/icons/${slug}.svg`)
  icons['brand-' + key] = svg.replace(/<title>.*?<\/title>/, '').replace('<svg ', '<svg fill="currentColor" ')
  brandHex[key] = '#' + (hexBySlug[slug] || 'FFFFFF')
}

writeFileSync(
  `${root}assets/icons.js`,
  `// Generated by scripts/build-icons.mjs — Phosphor duotone (MIT) + Simple Icons (CC0)\n` +
    `window.__ICONS = ${JSON.stringify(icons)};\nwindow.__BRAND_HEX = ${JSON.stringify(brandHex)};\n`,
)
console.log(`icons: ${Object.keys(FEATURE).length} feature + ${Object.keys(BRANDS).length} brands`, brandHex)
